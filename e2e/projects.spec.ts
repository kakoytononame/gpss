import { expect, test, type APIRequestContext } from '@playwright/test';
import { openFreshApp } from './helpers';

const PROJECTS = '/api/alina-gpss/studio/projects';

const port = (Id: number, Mode: string) => ({ Id, Mode, ConnectionsLimit: 0, TransferMode: 'DirectOrSplit', Side: 1, Position: 0.5 });

/** Creates a project with a composite TEB through the API (as an imported GPSS Studio project would look). */
async function createProject(request: APIRequestContext, name: string) {
  const created = await (await request.post(PROJECTS, { data: { Name: name } })).json();
  const scheme = {
    Nodes: [
      {
        Id: 'src',
        Kind: 'simple',
        Header: 'Поступление заказов',
        NameInModel: 'teb1',
        X: 80,
        Y: 60,
        Width: 180,
        Height: 60,
        GpssText: ' GENERATE 4',
        Outputs: [port(2, 'LastBlock')],
      },
      {
        Id: 'shop',
        Kind: 'composite',
        Header: 'Цех',
        NameInModel: 'teb2',
        X: 80,
        Y: 220,
        Width: 180,
        Height: 70,
        Inputs: [port(1, 'FirstBlock')],
        Child: {
          Nodes: [
            {
              Id: 'machine',
              Kind: 'simple',
              Header: 'Станок',
              NameInModel: 'teb3',
              X: 300,
              Y: 120,
              Width: 160,
              Height: 60,
              GpssText: ' SEIZE Machine\n ADVANCE 3\n RELEASE Machine\n TERMINATE 1',
              Inputs: [port(1, 'FirstBlock')],
            },
          ],
          Links: [{ Id: 'in', FromNodeId: 'boundary:in', FromPortId: 0, ToNodeId: 'machine', ToPortId: 1 }],
          Boundary: [{ Id: 'boundary:in', Direction: 'input', DefinitionId: 1 }],
        },
      },
    ],
    Links: [{ Id: 'l1', FromNodeId: 'src', FromPortId: 2, ToNodeId: 'shop', ToPortId: 1 }],
  };
  await request.put(`${PROJECTS}/${created.Id}`, { data: { Id: created.Id, Name: name, Models: [{ Name: 'Основная', IsCurrent: true, Scheme: scheme }] } });
  return created.Id as string;
}

test.describe('Simulation projects', () => {
  test('opens a project, navigates into a composite TEB, generates and runs the model', async ({ page }) => {
    const name = `Мастерская e2e ${Date.now()}`;
    const id = await createProject(page.request, name);
    await openFreshApp(page);

    await page.getByRole('button', { name: 'Открыть проект / Управление' }).click();
    await page.locator('.projects-table tr', { hasText: name }).getByRole('button', { name: 'Открыть' }).click();

    await expect(page.locator('.scheme-breadcrumb')).toContainText(`${name} › Основная`);
    await expect(page.locator('.scheme-node')).toHaveCount(2);
    await expect(page.locator('.tree-row', { hasText: 'Основная (текущая модель)' })).toBeVisible();

    await page.locator('.scheme-node--composite').dblclick();
    await expect(page.locator('.scheme-breadcrumb')).toContainText('› Цех');
    await expect(page.locator('.scheme-node', { hasText: 'Станок' })).toBeVisible();

    await page.getByRole('button', { name: 'Собрать текст GPSS модели по структурной схеме' }).click();
    await expect(page.locator('.global-status')).toContainText('Текст модели сгенерирован');
    await expect(page.getByRole('textbox', { name: 'Текст GPSS модели' })).toHaveValue(/teb3_autoGenerated1_firstBlock SEIZE teb3_Machine/);

    await page.getByRole('textbox', { name: 'Текст GPSS модели' }).press('End');
    await page.getByRole('textbox', { name: 'Текст GPSS модели' }).pressSequentially('\nSTART 5');
    await page.getByRole('button', { name: 'Запустить моделирование' }).first().click();
    await expect(page.locator('.global-status')).toContainText('завершено');

    // TEB tests check every TEB of the model, including the one inside the composite TEB.
    await page.getByRole('tab', { name: 'Тесты ТЭБов' }).click();
    await page.getByRole('button', { name: 'Запустить тесты' }).click();
    await expect(page.locator('.global-status')).toContainText(/Тесты ТЭБов: пройдено \d+ из \d+/);
    const machine = page.getByRole('region', { name: 'Станок' });
    await expect(machine).toContainText('Входы и выходы');
    await page.getByRole('region', { name: 'Поступление заказов' }).getByText('Описание ТЭБа').click();
    await expect(page.locator('.scheme-breadcrumb')).not.toContainText('› Цех');
    await machine.getByText('GPSS-модель').click();
    await expect(page.locator('.scheme-breadcrumb')).toContainText('› Цех');

    await page.request.delete(`${PROJECTS}/${id}`);
  });

  test('imports a model file', async ({ page }) => {
    await openFreshApp(page);
    await page.getByRole('button', { name: 'Открыть проект / Управление' }).click();

    await page.locator('input[aria-label="Файл проекта GPSS Studio"]').setInputFiles({
      name: 'kassa.gps',
      mimeType: 'application/octet-stream',
      buffer: Buffer.from(' GENERATE 10\n SEIZE Kassa\n ADVANCE 6\n RELEASE Kassa\n TERMINATE 1\n START 10\n'),
    });

    await expect(page.locator('.global-status')).toContainText('Проект «kassa» импортирован');
    await expect(page.getByRole('textbox', { name: 'Текст GPSS модели' })).toHaveValue(/SEIZE Kassa/);

    const project = await (await page.request.get(PROJECTS)).json();
    const imported = project.find((item: { Name: string }) => item.Name === 'kassa');
    expect(imported).toBeTruthy();
    await page.request.delete(`${PROJECTS}/${imported.Id}`);
  });

  test('edits a form, runs it and shows the dynamic form', async ({ page }) => {
    const name = `Порт e2e ${Date.now()}`;
    const created = await (await page.request.post(PROJECTS, { data: { Name: name } })).json();
    const control = (Type: string, extra: object) => ({
      Type,
      Name: Type,
      X: 0,
      Y: 0,
      Width: 90,
      Height: 22,
      FontSize: 9,
      Choices: [],
      Intervals: [],
      Series: [],
      Children: [],
      ...extra,
    });
    const form = {
      Name: 'Порт',
      ModelText: 'Berth STORAGE 2\nINITIAL X$Gap,10\n GENERATE X$Gap\n ENTER Berth\n ADVANCE 15\n LEAVE Berth\n TERMINATE 1\n',
      HasAnimation: false,
      Inputs: [
        {
          Number: 1,
          Name: '(2) INITIAL',
          Kind: 'command',
          Operator: 'initial',
          Line: 2,
          Operands: [{ Name: 'Интервал', Operand: 'B', ValueType: 'Numeric', Value: '10', DefaultValue: '10' }],
        },
      ],
      Indicators: [{ Id: 5, Title: 'Причал', Object: 'Berth', ObjectType: 'Storage', Sna: 'S', Expression: 'S$Berth', Monitored: true }],
      Run: { StartCount: 20, CollectDynamics: true, MonitorInterval: 10 },
      Plan: null,
      EntryForm: control('panel', {
        Width: 400,
        Height: 120,
        Children: [
          control('label', { Text: 'Интервал прихода', X: 5, Y: 5, Width: 140 }),
          control('input', { Name: 'Интервал прихода (поле)', X: 160, Y: 5, Input: 1, Operand: 'B' }),
        ],
      }),
      DynamicForm: control('panel', { Width: 400, Height: 120, Children: [control('sna', { Name: 'Занято мест', X: 10, Y: 10, Indicator: 5 })] }),
      Images: {},
    };
    await page.request.put(`${PROJECTS}/${created.Id}`, {
      data: { Id: created.Id, Name: name, Models: [{ Name: 'Порт', IsCurrent: true, ModelText: form.ModelText, Forms: ['Порт'], UserForms: [form] }] },
    });
    await openFreshApp(page);

    await page.getByRole('button', { name: 'Открыть проект / Управление' }).click();
    await page.locator('.projects-table tr', { hasText: name }).getByRole('button', { name: 'Открыть' }).click();
    await page.locator('.tree-row', { hasText: 'Форма ввода данных' }).click();

    await expect(page.getByText('Интервал прихода', { exact: true })).toBeVisible();
    await page.getByRole('textbox', { name: 'Интервал прихода (поле)' }).fill('8');
    await page.getByRole('button', { name: 'Записать исходные данные в текст модели' }).click();
    await expect(page.getByRole('textbox', { name: 'Текст GPSS модели' })).toHaveValue(/INITIAL X\$Gap,8/);

    await page.locator('.tree-row', { hasText: 'Форма ввода данных' }).click();
    await page.getByRole('button', { name: 'Сформировать модель и выполнить моделирование' }).click();
    await expect(page.locator('.global-status')).toContainText('завершено');
    await expect(page.getByRole('heading', { name: /Динамическая форма/ })).toBeVisible();
    await expect(page.locator('output[aria-label="Занято мест"]')).toHaveText(/^[0-2]$/);
    await expect(page.getByRole('region', { name: 'Динамика показателей' })).toContainText('Причал (S$Berth)');

    // The run is saved as a single experiment of the project and opens from the result tree.
    await expect(page.locator('.global-status')).toContainText('сохранён');
    await page.locator('.tree-row', { hasText: 'Эксперимент «Порт»' }).click();
    const details = page.locator('.results-detail');
    await expect(details.getByRole('heading', { name: /Эксперимент «Порт»/ })).toBeVisible();
    await details.getByRole('tab', { name: 'Исходные данные' }).click();
    await expect(details.getByRole('tabpanel', { name: 'Исходные данные' })).toContainText('Интервал');
    await expect(details.getByRole('tabpanel', { name: 'Исходные данные' })).toContainText('8');
    await details.getByRole('tab', { name: 'Динамика показателей' }).click();
    await expect(details.getByRole('tabpanel', { name: 'Динамика показателей' })).toContainText('Причал (S$Berth)');

    // The chart of the tab goes to the final report as a picture; the report is exported for Word.
    await details.getByRole('button', { name: 'Добавить в отчёт' }).click();
    await expect(page.locator('.global-status')).toContainText('добавлено фрагментов: 1');
    await page.locator('.tree-row', { hasText: 'Итоговый отчёт' }).click();
    const fragment = page.getByRole('listitem', { name: 'Фрагмент 1' });
    await expect(fragment.getByRole('textbox', { name: 'Заголовок фрагмента' })).toHaveValue('Причал (S$Berth)');
    await expect(fragment.locator('img')).toHaveAttribute('src', /^data:image\/png;base64,/);

    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Сохранить отчёт как документ Word (.doc) с графиками' }).click();
    const file = await download;
    expect(file.suggestedFilename()).toBe(`Отчёт по проекту «${name}».doc`);
    const content = await (await file.createReadStream()).toArray();
    expect(Buffer.concat(content).toString('utf8')).toContain('Content-Location: file:///C:/gpss-report/image001.png');
    await page.request.delete(`${PROJECTS}/${created.Id}`);
  });
});
