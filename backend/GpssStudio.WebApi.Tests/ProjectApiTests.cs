using System.IO.Compression;
using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text;
using System.Text.Json;

namespace GpssStudio.WebApi.Tests;

public sealed class ProjectApiTests : ApiTestBase
{
    private const string ProjectsPath = "/api/alina-gpss/studio/projects";

    private static ByteArrayContent Zip(params (string Name, string Content)[] entries)
    {
        using var buffer = new MemoryStream();
        using (var zip = new ZipArchive(buffer, ZipArchiveMode.Create, leaveOpen: true))
        {
            foreach (var (name, content) in entries)
            {
                using var writer = new StreamWriter(zip.CreateEntry(name).Open(), new UTF8Encoding(false));
                writer.Write(content);
            }
        }

        return new ByteArrayContent(buffer.ToArray());
    }

    private async Task<HttpResponseMessage> Upload(HttpContent file, string fileName)
    {
        file.Headers.ContentType = new MediaTypeHeaderValue("application/octet-stream");
        using var form = new MultipartFormDataContent { { file, "file", fileName } };
        return await Client.PostAsync($"{ProjectsPath}/import", form);
    }

    private static object Scheme() => new
    {
        Nodes = new object[]
        {
            new { Id = "a", NameInModel = "teb1", Kind = "simple", Header = "Источник", GpssText = " GENERATE 4", Outputs = new[] { new { Id = 2, Mode = "LastBlock" } } },
            new { Id = "b", NameInModel = "teb2", Kind = "simple", Header = "Касса", GpssText = " SEIZE Cash\n ADVANCE 3\n RELEASE Cash\n TERMINATE 1", Inputs = new[] { new { Id = 1, Mode = "FirstBlock" } } },
        },
        Links = new[] { new { FromNodeId = "a", FromPortId = 2, ToNodeId = "b", ToPortId = 1 } },
    };

    [Fact]
    public async Task CreateSaveListAndDelete_RoundTripTheProjectDocument()
    {
        var created = await Client.PostAsJsonAsync(ProjectsPath, new { Name = "Банк", Description = "Очередь в банке" });
        Assert.Equal(HttpStatusCode.Created, created.StatusCode);
        var project = await ReadJsonAsync(created);
        var id = project.GetProperty("Id").GetString();
        Assert.Equal("Модель 1", project.GetProperty("Models")[0].GetProperty("Name").GetString());

        var document = new { Id = id, Name = "Банк 2", Models = new[] { new { Name = "Основная", Scheme = Scheme() } } };
        var saved = await Client.PutAsJsonAsync($"{ProjectsPath}/{id}", document);
        Assert.Equal(HttpStatusCode.OK, saved.StatusCode);

        var loaded = await ReadJsonAsync(await Client.GetAsync($"{ProjectsPath}/{id}"));
        Assert.Equal("Банк 2", loaded.GetProperty("Name").GetString());
        Assert.Equal(" GENERATE 4", loaded.GetProperty("Models")[0].GetProperty("Scheme").GetProperty("Nodes")[0].GetProperty("GpssText").GetString());

        var list = await ReadJsonAsync(await Client.GetAsync(ProjectsPath));
        Assert.Contains(list.EnumerateArray(), item => item.GetProperty("Id").GetString() == id && item.GetProperty("ModelCount").GetInt32() == 1);

        Assert.Equal(HttpStatusCode.NoContent, (await Client.DeleteAsync($"{ProjectsPath}/{id}")).StatusCode);
        Assert.Equal(HttpStatusCode.NotFound, (await Client.GetAsync($"{ProjectsPath}/{id}")).StatusCode);
    }

    [Fact]
    public async Task GenerateForStoredModel_ReturnsRunnableText()
    {
        var project = await ReadJsonAsync(await Client.PostAsJsonAsync(ProjectsPath, new { Name = "Касса" }));
        var id = project.GetProperty("Id").GetString();
        await Client.PutAsJsonAsync($"{ProjectsPath}/{id}", new { Id = id, Name = "Касса", Models = new[] { new { Name = "М", Scheme = Scheme() } } });

        var result = await ReadJsonAsync(await Client.PostAsync($"{ProjectsPath}/{id}/models/0/generate", null));

        Assert.True(result.GetProperty("Success").GetBoolean());
        var text = result.GetProperty("Text").GetString()!;
        Assert.Contains("teb2_autoGenerated1_firstBlock SEIZE teb2_Cash", text);

        var session = await ReadJsonAsync(await Client.PostAsJsonAsync("/api/alina-gpss/studio/simulation/sessions", new { text = text + "START 5\n" }));
        Assert.Equal("completed", session.GetProperty("State").GetString());
        Assert.Equal(HttpStatusCode.NotFound, (await Client.PostAsync($"{ProjectsPath}/{id}/models/3/generate", null)).StatusCode);
    }

    [Fact]
    public async Task Generate_FromUnsavedScheme_ReportsProblemsPerTeb()
    {
        var response = await Client.PostAsJsonAsync($"{ProjectsPath}/generate", new
        {
            ModelName = "Черновик",
            Scheme = new
            {
                Nodes = new object[]
                {
                    new { Id = "x", NameInModel = "teb1", Kind = "simple", Header = "Генератор", GpssText = " GENERATE 1", Outputs = new[] { new { Id = 2, Mode = "LastBlock" } } },
                    new { Id = "y", NameInModel = "teb2", Kind = "simple", Header = "Приёмник", GpssText = " TERMINATE 1", Inputs = new[] { new { Id = 1, Mode = "Label", Label = "Missing" } } },
                },
                Links = new[] { new { FromNodeId = "x", FromPortId = 2, ToNodeId = "y", ToPortId = 1 } },
            },
        });

        var result = await ReadJsonAsync(response);
        Assert.False(result.GetProperty("Success").GetBoolean());
        Assert.Contains(result.GetProperty("Messages").EnumerateArray(), message => message.GetProperty("Teb").GetString() == "Приёмник");
        Assert.Contains("* Имитационная модель: «Черновик»", result.GetProperty("Text").GetString());

        Assert.Equal(HttpStatusCode.BadRequest, (await Client.PostAsJsonAsync($"{ProjectsPath}/generate", new { ModelName = "x" })).StatusCode);
    }

    [Fact]
    public async Task Import_ReadsProjectArchive()
    {
        const string projectFile = """
            <?xml version="1.0" encoding="utf-8"?>
            <GpssStudioProject FormatVersion="1"><Name>Импорт</Name><SimModels><SimModel><Name>Модель А</Name></SimModel></SimModels></GpssStudioProject>
            """;
        var response = await Upload(Zip(("Импорт/Project.gsproj", projectFile), ("Импорт/SimModels/Модель А/ModelText.gps", " GENERATE 2\n TERMINATE 1\n START 3\n")), "project.zip");

        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var project = await ReadJsonAsync(response);
        Assert.Equal("Импорт", project.GetProperty("Name").GetString());
        var model = project.GetProperty("Models")[0];
        Assert.Equal("Модель А", model.GetProperty("Name").GetString());
        Assert.Contains("GENERATE 2", model.GetProperty("ModelText").GetString());
        Assert.Equal(JsonValueKind.Null, model.GetProperty("Scheme").ValueKind);

        var stored = await Client.GetAsync($"{ProjectsPath}/{project.GetProperty("Id").GetString()}");
        Assert.Equal(HttpStatusCode.OK, stored.StatusCode);
    }

    [Fact]
    public async Task Import_AcceptsSingleModelFileAndRejectsGarbage()
    {
        var single = await Upload(new ByteArrayContent(Encoding.UTF8.GetBytes(" GENERATE 1\n TERMINATE 1\n")), "Касса.gps");
        Assert.Equal(HttpStatusCode.Created, single.StatusCode);
        Assert.Equal("Касса", (await ReadJsonAsync(single)).GetProperty("Name").GetString());

        var garbage = await Upload(new ByteArrayContent([1, 2, 3, 4]), "broken.zip");
        Assert.Equal(HttpStatusCode.BadRequest, garbage.StatusCode);

        var empty = await Upload(Zip(("readme.txt", "nothing")), "empty.zip");
        Assert.Equal(HttpStatusCode.BadRequest, empty.StatusCode);
    }
}
