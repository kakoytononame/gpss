using GpssStudio.Projects.Generation;
using GpssStudio.Projects.Model;
using GpssStudio.Simulation;

namespace GpssStudio.Projects.Tests;

public sealed class GeneratorTests
{
    private static TebNode Teb(string name, string header, string text, IEnumerable<TebPort>? inputs = null, IEnumerable<TebPort>? outputs = null) => new()
    {
        Id = name, NameInModel = name, Header = header, Kind = TebKinds.Simple, GpssText = text,
        Inputs = inputs?.ToList() ?? [], Outputs = outputs?.ToList() ?? [],
    };

    private static TebPort FirstBlock(int id = 1) => new() { Id = id, Mode = ConnectedBlockModes.FirstBlock };

    private static TebPort LastBlock(int id = 2, string mode = TransferModes.DirectOrSplit) => new() { Id = id, Mode = ConnectedBlockModes.LastBlock, TransferMode = mode };

    private static TebPort LabelPort(int id, string label) => new() { Id = id, Mode = ConnectedBlockModes.Label, Label = label };

    private static TebLink Link(string from, int fromPort, string to, int toPort = 1) => new() { FromNodeId = from, FromPortId = fromPort, ToNodeId = to, ToPortId = toPort };

    private static List<string> Lines(GenerationResult result) => result.Text.Split('\n').ToList();

    /// <summary>A small port-like model: arrivals, a 50/50 decision with output labels, two services and data.</summary>
    private static TebScheme PortScheme() => new()
    {
        Nodes =
        [
            Teb("teb1", "Прибытие", " GENERATE 10", outputs: [LastBlock()]),
            Teb("teb2", "Выбор причала", " TRANSFER .5,small,large ;half", [FirstBlock()], [LabelPort(2, "small"), LabelPort(3, "large")]),
            Teb("teb3", "Малый причал", " ENTER Berth\n ADVANCE 3\n LEAVE Berth\n TRANSFER ,done", [FirstBlock()], [LabelPort(2, "done")]),
            Teb("teb4", "Большой причал", "Again SEIZE Crane\n ADVANCE 4\n RELEASE Crane\n TERMINATE 1", [FirstBlock()]),
            Teb("teb5", "Уход", " SAVEVALUE Gone+,1\n TERMINATE 1\n START 20", [FirstBlock()]),
            new TebNode
            {
                Id = "data", Kind = TebKinds.Data, Header = "Данные",
                Entities =
                [
                    new DataEntity { Type = DataEntityTypes.Equ, Name = "Berth", Value = "1" },
                    new DataEntity { Type = DataEntityTypes.Storage, Name = "Berth", Value = "2" },
                    new DataEntity { Type = DataEntityTypes.BVariable, Name = "Free", Value = "R$Berth'GE'1" },
                    new DataEntity { Type = DataEntityTypes.Savevalue, Name = "Rate", Value = "26" },
                    new DataEntity { Type = DataEntityTypes.Matrix, Name = "Plan", Cells = [["1", "0"], ["", "Berth"]] },
                ],
            },
        ],
        Links = [Link("teb1", 2, "teb2"), Link("teb2", 2, "teb3"), Link("teb2", 3, "teb4"), Link("teb3", 2, "teb5")],
    };

    [Fact]
    public void Generate_AppliesNameCorrectionAndTransitions()
    {
        var result = ModelGenerator.Generate(PortScheme(), "Порт");
        var lines = Lines(result);

        Assert.True(result.Success, string.Join("\n", result.Messages));
        Assert.Equal("* Имитационная модель: «Порт»", lines[1]);
        // Data TEB: definitions in list order, global names are not prefixed.
        Assert.Contains("Berth EQU 1", lines);
        Assert.Contains("Berth STORAGE 2", lines);
        Assert.Contains("Free BVARIABLE (R$Berth'GE'1)", lines);
        Assert.Contains("INITIAL X$Rate,26", lines);
        Assert.Contains("Plan MATRIX ,2,2", lines);
        Assert.Contains("INITIAL MX$Plan(2,2),Berth", lines);
        Assert.DoesNotContain(lines, line => line.StartsWith("INITIAL MX$Plan(2,1)", StringComparison.Ordinal));
        // Output labels lead to the first blocks of the connected TEBs, which get generated labels.
        Assert.Contains("teb2_autoGenerated1_firstBlock TRANSFER .5,teb3_autoGenerated2_firstBlock,teb4_Again ;half", lines);
        Assert.Contains("teb3_autoGenerated2_firstBlock ENTER Berth", lines);
        Assert.Contains("teb4_Again SEIZE teb4_Crane", lines);
        // The fractional TRANSFER cannot fall through, but GPSS Studio still closes the TEB with TERMINATE.
        Assert.Equal("TERMINATE", lines[lines.IndexOf("teb2_autoGenerated1_firstBlock TRANSFER .5,teb3_autoGenerated2_firstBlock,teb4_Again ;half") + 1]);
        // teb1 falls through into teb2: no TRANSFER is needed.
        Assert.DoesNotContain(lines, line => line == "TRANSFER ,teb2_autoGenerated1_firstBlock");
        // START written inside a TEB is moved to the end of the model.
        Assert.Equal("START 20", lines.Last(line => line.Length > 0));
    }

    [Fact]
    public void Generate_ModelRunsInTheSimulator()
    {
        var result = ModelGenerator.Generate(PortScheme(), "Порт");
        var (session, run) = SimulationSession.Create(result.Text, "Порт");

        Assert.True(run.Success, run.RuntimeError + string.Join("; ", run.Errors));
        Assert.Equal("completed", run.State);
        Assert.True(session!.Engine.Savevalue("teb5_Gone").Value > 0);
    }

    [Fact]
    public void Generate_SeveralConnectionsUseSplitCopies()
    {
        var scheme = new TebScheme
        {
            Nodes =
            [
                Teb("a", "Источник", " GENERATE ,,,1", outputs: [LastBlock()]),
                Teb("b", "Ветвь 1", " TERMINATE 1", [FirstBlock()]),
                Teb("c", "Ветвь 2", " TERMINATE", [FirstBlock()]),
                Teb("d", "Ветвь 3", " TERMINATE", [FirstBlock()]),
            ],
            Links = [Link("a", 2, "b"), Link("a", 2, "c"), Link("a", 2, "d")],
        };

        var lines = Lines(ModelGenerator.Generate(scheme, "M"));

        var start = lines.IndexOf("* Выход №1");
        Assert.True(start > 0);
        Assert.Equal("a_autoGenerated_output1 SPLIT 1,c_autoGenerated2_firstBlock", lines[start + 1]);
        Assert.Equal("SPLIT 1,d_autoGenerated3_firstBlock", lines[start + 2]);
        // The original transaction continues into the first connection, emitted right after.
        Assert.Equal("b_autoGenerated1_firstBlock TERMINATE 1", lines.First(line => line.StartsWith("b_", StringComparison.Ordinal)));
    }

    [Fact]
    public void Generate_RandomAndFirstAvailableModes()
    {
        TebScheme Scheme(string mode) => new()
        {
            Nodes =
            [
                Teb("a", "Источник", " GENERATE 1", outputs: [LastBlock(2, mode)]),
                Teb("b", "B", " SEIZE F1\n RELEASE F1\n TERMINATE 1", [FirstBlock()]),
                Teb("c", "C", " TERMINATE 1", [FirstBlock()]),
                Teb("d", "D", " TERMINATE 1", [FirstBlock()]),
            ],
            Links = [Link("a", 2, "b"), Link("a", 2, "c"), Link("a", 2, "d")],
        };

        var random = Lines(ModelGenerator.Generate(Scheme(TransferModes.Random), "M"));
        Assert.Contains("a_autoGenerated_output1 TRANSFER 0.333333333333333,,b_autoGenerated1_firstBlock", random);
        Assert.Contains("TRANSFER 0.5,,c_autoGenerated2_firstBlock", random);
        Assert.Contains("TRANSFER ,d_autoGenerated3_firstBlock", random);

        var first = Lines(ModelGenerator.Generate(Scheme(TransferModes.FirstAvailable), "M"));
        Assert.Contains("a_autoGenerated_output1 TRANSFER BOTH,b_autoGenerated1_firstBlock,a_autoGenerated_output1_2", first);
        Assert.Contains("a_autoGenerated_output1_2 TRANSFER BOTH,c_autoGenerated2_firstBlock,d_autoGenerated3_firstBlock", first);
    }

    [Fact]
    public void Generate_ConnectionModelBecomesASeparateFragment()
    {
        var scheme = new TebScheme
        {
            Nodes = [Teb("a", "A", " GENERATE 5", outputs: [LastBlock()]), Teb("b", "B", " TERMINATE 1", [FirstBlock()])],
            Links = [new TebLink { FromNodeId = "a", FromPortId = 2, ToNodeId = "b", ToPortId = 1, GpssText = " ADVANCE 2\n SAVEVALUE Moved+,1", Description = "Дорога" }],
        };

        var result = ModelGenerator.Generate(scheme, "M");
        var lines = Lines(result);

        Assert.Contains("* Соединение «Дорога»", lines);
        Assert.Contains("connection1_autoGenerated1_firstBlock ADVANCE 2", lines);
        Assert.Contains("SAVEVALUE connection1_Moved+,1", lines);
        // A falls through into the fragment and the fragment into B: both jumps are optimised away.
        Assert.DoesNotContain(lines, line => line.StartsWith("TRANSFER", StringComparison.Ordinal));
        Assert.True(lines.IndexOf("connection1_autoGenerated1_firstBlock ADVANCE 2") < lines.IndexOf("b_autoGenerated1_firstBlock TERMINATE 1"));
        Assert.True(result.Success, string.Join("\n", result.Messages));
    }

    [Fact]
    public void Generate_CompositeScopesDataAndCrossesBoundaries()
    {
        var inner = new TebScheme
        {
            Nodes =
            [
                new TebNode { Id = "d", Kind = TebKinds.Data, Header = "Данные цеха", Entities = [new DataEntity { Type = DataEntityTypes.Storage, Name = "Team", Value = "3" }] },
                Teb("w", "Работа", " ENTER Team\n ADVANCE 2\n LEAVE Team", [FirstBlock()], [LastBlock()]),
            ],
            Boundary = [new BoundaryConnector { Id = "boundary:in", Direction = "input", DefinitionId = 1 }, new BoundaryConnector { Id = "boundary:out", Direction = "output", DefinitionId = 2 }],
            Links = [Link("boundary:in", 0, "w"), Link("w", 2, "boundary:out", 0)],
        };
        var scheme = new TebScheme
        {
            Nodes =
            [
                Teb("src", "Заказы", " GENERATE 3", outputs: [LastBlock()]),
                new TebNode { Id = "shop", NameInModel = "teb7", Kind = TebKinds.Composite, Header = "Цех", Child = inner, Inputs = [FirstBlock()], Outputs = [LastBlock()] },
                Teb("end", "Выход", " TERMINATE 1", [FirstBlock()]),
            ],
            Links = [Link("src", 2, "shop"), Link("shop", 2, "end")],
        };

        var result = ModelGenerator.Generate(scheme, "M");
        var lines = Lines(result);

        Assert.True(result.Success, string.Join("\n", result.Messages));
        Assert.Contains("* ТЭБ «Цех»", lines);
        Assert.Contains("teb7_Team STORAGE 3", lines);
        Assert.Contains("w_autoGenerated1_firstBlock ENTER teb7_Team", lines);
        Assert.Contains("LEAVE teb7_Team", lines);
        Assert.Contains("end_autoGenerated2_firstBlock TERMINATE 1", lines);
    }

    [Fact]
    public void Generate_ReportsMissingLabelsAndUnconnectedOutputs()
    {
        var scheme = new TebScheme
        {
            Nodes =
            [
                Teb("a", "A", " GENERATE 5", outputs: [LastBlock()]),
                Teb("b", "B", " ADVANCE 1\n TERMINATE 1", [new TebPort { Id = 1, Mode = ConnectedBlockModes.Label, Label = "Nowhere" }], [LabelPort(2, "out")]),
            ],
            Links = [Link("a", 2, "b")],
        };

        var result = ModelGenerator.Generate(scheme, "M");

        Assert.False(result.Success);
        Assert.Contains(result.Messages, message => message.Severity == GenerationMessage.Error && message.Message.Contains("Nowhere") && message.Teb == "B");
        Assert.Contains(result.Messages, message => message.Severity == GenerationMessage.Warning && message.Message.Contains("не соединён"));
    }

    [Fact]
    public void Generate_SubstitutesTebParametersAndKeepsTransactionParameters()
    {
        var node = Teb("srv", "Обслуживание", " GENERATE ServiceTime\n ASSIGN Count+,1\n ASSIGN Kind,P$Count\n SAVEVALUE Total+,P$Kind\n TERMINATE 1");
        node.Parameters = [new TebParameter { Id = 1, NameInModel = "ServiceTime", DefaultValue = "5", Value = "7" }];

        var lines = Lines(ModelGenerator.Generate(new TebScheme { Nodes = [node] }, "M"));

        Assert.Contains("GENERATE 7", lines);
        Assert.Contains("ASSIGN Count+,1", lines);
        Assert.Contains("ASSIGN Kind,P$Count", lines);
        Assert.Contains("SAVEVALUE srv_Total+,P$Kind", lines);
    }

    [Theory]
    [InlineData("TEST E BV$Var2,1,Out", "TEST E BV$Var2,1,t_Out")]
    [InlineData("ADVANCE (Exponential(1,0,X$Mean))", "ADVANCE (Exponential(1,0,X$Mean))")]
    [InlineData("TEST G (Q$Line+N$Out*2),FN$Dist", "TEST G (Q$t_Line+N$t_Out*2),FN$t_Dist")]
    [InlineData("SEIZE FN*Selector", "SEIZE FN*Selector")]
    [InlineData("SAVEVALUE Busy,(F$Crane 'AND' Q2'E'0)", "SAVEVALUE t_Busy,(F$t_Crane 'AND' Q2'E'0)")]
    [InlineData("TRANSFER SBR,Out,Back", "TRANSFER SBR,t_Out,Back")]
    [InlineData("LINK Chain,FIFO,Out", "LINK t_Chain,FIFO,t_Out")]
    [InlineData("ENTER Pool,2", "ENTER Pool,2")]
    public void NameCorrector_HandlesOperandRoles(string source, string expected)
    {
        var corrector = new NameCorrector(
            "t_",
            new HashSet<string>(["Out"], StringComparer.OrdinalIgnoreCase),
            new Dictionary<string, string>(),
            new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase) { ["Var2"] = "Var2", ["Mean"] = "Mean", ["Pool"] = "Pool" },
            new Dictionary<string, string>());

        Assert.Equal(expected, corrector.Correct(StatementLine.Parse(source)).Render());
    }
}
